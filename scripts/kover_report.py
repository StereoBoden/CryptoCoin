import xml.etree.ElementTree as ET
import os
import sys

def parse_kover_xml(xml_path):
    if not os.path.exists(xml_path):
        print(f"Kover XML report not found at {xml_path}")
        return None

    tree = ET.parse(xml_path)
    root = tree.getroot()

    counters = {}
    for child in root:
        if child.tag == 'counter':
            c_type = child.get('type')
            missed = int(child.get('missed', 0))
            covered = int(child.get('covered', 0))
            counters[c_type] = {'missed': missed, 'covered': covered, 'total': missed + covered}

    return counters

if __name__ == '__main__':
    xml_path = 'composeApp/build/reports/kover/report.xml'
    counters = parse_kover_xml(xml_path)
    if not counters:
        sys.exit(1)

    md = "## 📊 Kover Code Coverage Report\n\n"
    md += "| Metric | Covered | Missed | Total | Percentage |\n"
    md += "|---|---|---|---|---|\n"

    metrics = [
        ('INSTRUCTION', 'Instructions'),
        ('LINE', 'Lines'),
        ('BRANCH', 'Branches'),
        ('METHOD', 'Methods'),
        ('CLASS', 'Classes')
    ]

    for key, label in metrics:
        if key in counters:
            c = counters[key]
            covered = c['covered']
            missed = c['missed']
            total = c['total']
            pct = (covered / total * 100) if total > 0 else 0.0
            md += f"| **{label}** | {covered:,} | {missed:,} | {total:,} | **{pct:.2f}%** |\n"

    md += "\n*Generated by KotlinX Kover*\n"

    # Write to GitHub step summary if available
    summary_path = os.environ.get('GITHUB_STEP_SUMMARY')
    if summary_path:
        with open(summary_path, 'a') as f:
            f.write(md)

    print(md)

    with open('kover_comment.md', 'w') as f:
        f.write(md)
